import React, { useContext, useMemo, useState, useEffect } from 'react';
import { AppContext } from '../context/AppContext';
import { ShieldAlert, Users, Database, DollarSign, AlertTriangle } from 'lucide-react';
import { fetchAdminStats, fetchAdminFraudLogs } from '../lib/api';

export default function AdminDashboard() {
  const { events, fraudLogs: contextFraudLogs, userProfile, formatPrice, theme } = useContext(AppContext);
  const isLight = theme === 'light';

  const [backendStats, setBackendStats] = useState(null);
  const [liveFraudLogs, setLiveFraudLogs] = useState([]);

  useEffect(() => {
    let cancelled = false;
    fetchAdminStats()
      .then((st) => {
        if (!cancelled) setBackendStats(st);
      })
      .catch(() => {});

    fetchAdminFraudLogs()
      .then((logs) => {
        if (!cancelled && logs && logs.length > 0) {
          setLiveFraudLogs(
            logs.map((l) => ({
              id: `api-fraud-${l.id}`,
              timestamp: new Date(l.timestamp).toLocaleString(),
              type: l.type || 'Anomalous Transaction',
              severity: l.severity === 'high' ? 'High' : l.severity === 'medium' ? 'Medium' : 'Low',
              ip: l.ip || '127.0.0.1',
              user: `User #${l.event_id || 'N/A'}`,
              eventTitle: `Event ID: ${l.event_id}`,
              details: l.details || 'Blocked by Fraud Detection Agent.',
            }))
          );
        }
      })
      .catch(() => {});

    return () => {
      cancelled = true;
    };
  }, []);

  // Merge live fraud logs with context logs
  const displayFraudLogs = useMemo(() => {
    if (liveFraudLogs.length > 0) return liveFraudLogs;
    return contextFraudLogs;
  }, [liveFraudLogs, contextFraudLogs]);

  // Stats calculation (use real backend stats if available)
  const totalRevenue = useMemo(() => {
    if (backendStats && backendStats.gross_revenue !== undefined) {
      return backendStats.gross_revenue;
    }
    return events.reduce((sum, e) => sum + (e.ticketsSold * e.price), 0);
  }, [events, backendStats]);

  const totalBookingsCount = useMemo(() => {
    if (backendStats && backendStats.total_purchases !== undefined) {
      return backendStats.total_purchases;
    }
    return events.reduce((sum, e) => sum + e.ticketsSold, 0);
  }, [events, backendStats]);

  // Mock list of attendee preference clusters in the system
  const mockUserClusters = [
    { name: userProfile.name, email: userProfile.email, location: userProfile.location, interests: userProfile.preferences, budget: userProfile.budget, tier: userProfile.ticketTier },
    { name: 'Marcus Aurelius', email: 'marcus.philosophy@rome.it', location: 'Delhi', interests: ['Arts', 'Comedy'], budget: 150, tier: 'Platinum' },
    { name: 'Sarah Connor', email: 's.connor@cyberdyne.io', location: 'Mumbai', interests: ['Tech'], budget: 200, tier: 'Gold' },
    { name: 'Devon Miles', email: 'devon@flag.org', location: 'Bengaluru', interests: ['Tech', 'Music'], budget: 80, tier: 'Silver' },
    { name: 'Leslie Knope', email: 'lknope@pawnee.gov', location: 'Pune', interests: ['Comedy', 'Arts'], budget: 120, tier: 'Gold' }
  ];


  return (
    <div className={`flex-1 p-6 md:p-10 max-w-7xl mx-auto w-full space-y-10 text-left transition-colors ${
      isLight ? 'text-slate-800' : 'text-gray-200'
    }`}>
      
      {/* Header */}
      <section className={`border-b pb-6 ${isLight ? 'border-slate-200' : 'border-white/5'}`}>
        <h1 className={`text-3xl font-extrabold tracking-tight m-0 ${isLight ? 'text-slate-900' : 'text-white'}`}>Admin Controls</h1>
        <p className={`text-sm mt-1 ${isLight ? 'text-slate-500' : 'text-gray-400'}`}>Supervise user profiling indices, check transaction logs, and review warnings generated by the Fraud Agent.</p>
      </section>

      {/* Stats Summary cards */}
      <section className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-5">
        <div className={`border p-5 rounded-2xl flex items-center gap-4 transition-colors ${
          isLight ? 'bg-white border-slate-200 shadow-xs' : 'bg-[#1f2028] border-white/5'
        }`}>
          <div className="w-11 h-11 bg-purple-500/10 rounded-xl flex items-center justify-center text-purple-600 dark:text-purple-400">
            <Users className="w-6 h-6" />
          </div>
          <div>
            <span className="text-[10px] text-slate-400 font-mono block uppercase font-bold">Attendee Clusters</span>
            <span className={`text-lg font-bold font-mono ${isLight ? 'text-slate-900' : 'text-white'}`}>{mockUserClusters.length} Profiles</span>
          </div>
        </div>

        <div className={`border p-5 rounded-2xl flex items-center gap-4 transition-colors ${
          isLight ? 'bg-white border-slate-200 shadow-xs' : 'bg-[#1f2028] border-white/5'
        }`}>
          <div className="w-11 h-11 bg-emerald-500/10 rounded-xl flex items-center justify-center text-emerald-600 dark:text-emerald-400">
            <DollarSign className="w-6 h-6" />
          </div>
          <div>
            <span className="text-[10px] text-slate-400 font-mono block uppercase font-bold">Accumulated Gross</span>
            <span className={`text-lg font-bold font-mono ${isLight ? 'text-slate-900' : 'text-white'}`}>{formatPrice(totalRevenue)}</span>
          </div>
        </div>

        <div className={`border p-5 rounded-2xl flex items-center gap-4 transition-colors ${
          isLight ? 'bg-white border-slate-200 shadow-xs' : 'bg-[#1f2028] border-white/5'
        }`}>
          <div className="w-11 h-11 bg-indigo-500/10 rounded-xl flex items-center justify-center text-indigo-600 dark:text-indigo-400">
            <Database className="w-6 h-6" />
          </div>
          <div>
            <span className="text-[10px] text-slate-400 font-mono block uppercase font-bold">Total Purchases</span>
            <span className={`text-lg font-bold font-mono ${isLight ? 'text-slate-900' : 'text-white'}`}>{totalBookingsCount} Tickets</span>
          </div>
        </div>

        <div className={`border p-5 rounded-2xl flex items-center gap-4 transition-colors ${
          isLight ? 'bg-white border-slate-200 shadow-xs' : 'bg-[#1f2028] border-white/5'
        }`}>
          <div className="w-11 h-11 bg-rose-500/10 rounded-xl flex items-center justify-center text-rose-500">
            <ShieldAlert className="w-6 h-6 animate-pulse" />
          </div>
          <div>
            <span className="text-[10px] text-slate-400 font-mono block uppercase font-bold">Fraud Agent Warnings</span>
            <span className={`text-lg font-bold font-mono ${isLight ? 'text-slate-900' : 'text-white'}`}>{displayFraudLogs.length} Alarms</span>
          </div>
        </div>
      </section>

      {/* Main Splits */}
      <div className="grid grid-cols-1 lg:grid-cols-2 gap-8">
        
        {/* Fraud Log Dashboard */}
        <section className={`border rounded-2xl p-6 space-y-4 transition-colors ${
          isLight ? 'bg-white border-slate-200 shadow-xs' : 'bg-[#1f2028] border-white/5'
        }`}>
          <div className={`flex justify-between items-center pb-3 border-b ${
            isLight ? 'border-slate-100' : 'border-white/5'
          }`}>
            <div className="flex items-center gap-2">
              <ShieldAlert className="w-5 h-5 text-rose-500" />
              <h2 className={`text-base font-bold font-mono uppercase tracking-wider m-0 ${
                isLight ? 'text-slate-800' : 'text-gray-200'
              }`}>Fraud Detection Logs</h2>
            </div>
            <span className="text-[9px] text-rose-500 font-mono bg-rose-500/10 border border-rose-500/20 px-2 py-0.5 rounded-full uppercase font-bold">
              Agent Guard Active
            </span>
          </div>

          <div className="space-y-4 max-h-[420px] overflow-y-auto pr-1">
            {displayFraudLogs.length === 0 ? (
              <div className="text-center py-20 text-xs text-slate-400">
                No fraud incidents logged yet. Secure bookings active.
              </div>
            ) : (
              displayFraudLogs.map((log) => (

                <div key={log.id} className={`border p-4 rounded-xl space-y-2 text-xs ${
                  isLight ? 'bg-slate-50 border-slate-200' : 'bg-[#16171d] border-white/5'
                }`}>
                  <div className="flex justify-between items-center flex-wrap gap-2">
                    <span className="font-bold text-rose-500 font-mono text-[10px] uppercase flex items-center gap-1">
                      <AlertTriangle className="w-3.5 h-3.5" /> {log.type}
                    </span>
                    <div className="flex items-center gap-2">
                      <span className={`text-[8px] font-mono px-1.5 py-0.5 rounded-md font-bold ${
                        log.severity === 'High' ? 'bg-red-500/25 text-red-600 dark:text-red-400' : 'bg-amber-500/25 text-amber-600 dark:text-amber-400'
                      }`}>
                        {log.severity} Risk
                      </span>
                      <span className="text-[9px] text-slate-400 font-mono">{log.timestamp}</span>
                    </div>
                  </div>
                  
                  <p className={`leading-normal ${isLight ? 'text-slate-700' : 'text-gray-300'}`}>{log.details}</p>

                  <div className={`flex justify-between items-center border-t pt-2 text-[10px] text-slate-400 font-mono ${
                    isLight ? 'border-slate-200' : 'border-white/5'
                  }`}>
                    <span>IP: {log.ip}</span>
                    <span>UserRef: {log.user}</span>
                  </div>
                </div>
              ))
            )}
          </div>
        </section>

        {/* User Profiles Dashboard */}
        <section className={`border rounded-2xl p-6 space-y-4 transition-colors ${
          isLight ? 'bg-white border-slate-200 shadow-xs' : 'bg-[#1f2028] border-white/5'
        }`}>
          <div className={`flex justify-between items-center pb-3 border-b ${
            isLight ? 'border-slate-100' : 'border-white/5'
          }`}>
            <div className="flex items-center gap-2">
              <Users className="w-5 h-5 text-purple-600 dark:text-purple-400" />
              <h2 className={`text-base font-bold font-mono uppercase tracking-wider m-0 ${
                isLight ? 'text-slate-800' : 'text-gray-200'
              }`}>User Preferences Index</h2>
            </div>
            <span className="text-[9px] text-purple-600 dark:text-purple-400 font-mono bg-purple-500/10 border border-purple-500/20 px-2 py-0.5 rounded-full uppercase font-bold">
              Personalizer Active
            </span>
          </div>

          <div className="space-y-4 max-h-[420px] overflow-y-auto pr-1">
            {mockUserClusters.map((user, i) => (
              <div key={i} className={`border p-4 rounded-xl flex items-start gap-3 text-xs justify-between ${
                isLight ? 'bg-slate-50 border-slate-200' : 'bg-[#16171d] border-white/5'
              }`}>
                <div className="space-y-2 text-left">
                  <div className="space-y-0.5">
                    <div className="flex items-center gap-1.5">
                      <h4 className={`font-bold text-sm m-0 leading-none ${
                        isLight ? 'text-slate-900' : 'text-gray-200'
                      }`}>{user.name}</h4>
                      <span className="bg-purple-600/20 text-purple-600 dark:text-purple-400 font-mono font-bold text-[8px] px-1.5 rounded-full">
                        {user.tier}
                      </span>
                    </div>
                    <span className="text-slate-400 font-mono text-[10px] block">{user.email}</span>
                  </div>
                  
                  <div className="flex flex-wrap gap-1 font-mono text-[9px]">
                    {user.interests.map((pref) => (
                      <span key={pref} className={`px-2 py-0.5 rounded-md border font-semibold ${
                        isLight ? 'bg-white border-slate-200 text-purple-700' : 'bg-[#1f2028] border-white/5 text-purple-400'
                      }`}>
                        {pref}
                      </span>
                    ))}
                  </div>
                </div>

                <div className="text-right space-y-1 font-mono">
                  <div>
                    <span className="text-[9px] text-slate-400 block uppercase">Zone</span>
                    <span className={`text-xs font-semibold ${isLight ? 'text-slate-700' : 'text-gray-300'}`}>{user.location}</span>
                  </div>
                  <div>
                    <span className="text-[9px] text-slate-400 block uppercase">Budget Band</span>
                    <span className={`text-xs font-semibold ${isLight ? 'text-slate-700' : 'text-gray-300'}`}>{formatPrice(user.budget)}</span>
                  </div>
                </div>
              </div>
            ))}
          </div>
        </section>

      </div>
    </div>
  );
}
